"""Install and bind the product-safe Office V2 scene package.

The source PGM and inspection catalog are generated by the MuJoCo scene
repository and copied into this image as immutable product inputs.  This
bootstrap deliberately uses the ordinary Scene API upload/calibration/publish
workflow: it neither writes SQLite directly nor exposes evaluator-only object
truth.  A deterministic PCD is reconstructed from the occupancy grid so the
existing Scene Worker remains the sole producer of verified map artifacts.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import math
import os
from pathlib import Path
import time
from typing import Any, Mapping, Sequence

import httpx

from packages.scene_core import identity_calibration


BUNDLE_ROOT = Path(__file__).with_name("builtin") / "office_v2"
CATALOG_PATH = BUNDLE_ROOT / "inspection_catalog.json"
PGM_PATH = BUNDLE_ROOT / "office_v2.pgm"
YAML_PATH = BUNDLE_ROOT / "office_v2.yaml"


class OfficeV2BootstrapError(RuntimeError):
    """Raised when the immutable Office V2 package cannot be published."""


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _canonical_sha256(value: object) -> str:
    encoded = json.dumps(
        value,
        ensure_ascii=False,
        allow_nan=False,
        separators=(",", ":"),
        sort_keys=True,
    ).encode("utf-8")
    return _sha256(encoded)


def _pgm(path: Path) -> tuple[int, int, bytes]:
    raw = path.read_bytes()
    position = 0
    tokens: list[bytes] = []
    while len(tokens) < 4:
        while position < len(raw) and raw[position] in b" \t\r\n":
            position += 1
        if position >= len(raw):
            raise OfficeV2BootstrapError("Office V2 PGM header is incomplete")
        if raw[position : position + 1] == b"#":
            newline = raw.find(b"\n", position)
            if newline < 0:
                raise OfficeV2BootstrapError("Office V2 PGM comment is incomplete")
            position = newline + 1
            continue
        end = position
        while end < len(raw) and raw[end] not in b" \t\r\n":
            end += 1
        tokens.append(raw[position:end])
        position = end
    while position < len(raw) and raw[position] in b" \t\r\n":
        position += 1
    if tokens[0] != b"P5" or tokens[3] != b"255":
        raise OfficeV2BootstrapError("Office V2 map must be an 8-bit binary PGM")
    try:
        width, height = int(tokens[1]), int(tokens[2])
    except ValueError as exc:
        raise OfficeV2BootstrapError("Office V2 PGM dimensions are invalid") from exc
    cells = raw[position:]
    if width <= 0 or height <= 0 or len(cells) != width * height:
        raise OfficeV2BootstrapError("Office V2 PGM payload length is invalid")
    return width, height, cells


def load_bundle(root: Path = BUNDLE_ROOT) -> dict[str, Any]:
    catalog_path = root / CATALOG_PATH.name
    pgm_path = root / PGM_PATH.name
    yaml_path = root / YAML_PATH.name
    try:
        catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
        pgm = pgm_path.read_bytes()
        nav_yaml = yaml_path.read_bytes()
    except (OSError, json.JSONDecodeError) as exc:
        raise OfficeV2BootstrapError(f"cannot read Office V2 product bundle: {exc}") from exc
    if not isinstance(catalog, Mapping):
        raise OfficeV2BootstrapError("Office V2 inspection catalog must be an object")
    if catalog.get("schemaVersion") != "h-ide.office-inspection/1":
        raise OfficeV2BootstrapError("Office V2 inspection catalog schema is unsupported")
    if catalog.get("sceneId") != "office_v2" or catalog.get("containsObjectAnswers") is not False:
        raise OfficeV2BootstrapError("Office V2 catalog identity or trust boundary is invalid")
    map_binding = catalog.get("map")
    if not isinstance(map_binding, Mapping):
        raise OfficeV2BootstrapError("Office V2 catalog map binding is missing")
    if map_binding.get("imageSha256") != _sha256(pgm):
        raise OfficeV2BootstrapError("Office V2 catalog PGM hash does not match the bundle")
    if map_binding.get("yamlSha256") != _sha256(nav_yaml):
        raise OfficeV2BootstrapError("Office V2 catalog YAML hash does not match the bundle")
    regions = catalog.get("regions")
    route = catalog.get("route")
    if not isinstance(regions, list) or not regions or not isinstance(route, list):
        raise OfficeV2BootstrapError("Office V2 catalog regions or route are missing")
    forbidden = {
        "objects",
        "objectId",
        "object_id",
        "targets",
        "semanticTests",
        "evaluation",
        "oracle",
    }

    def reject_privileged(value: object) -> None:
        if isinstance(value, Mapping):
            for key, nested in value.items():
                if str(key) in forbidden:
                    raise OfficeV2BootstrapError(
                        f"Office V2 product catalog contains forbidden key {key}"
                    )
                reject_privileged(nested)
        elif isinstance(value, list):
            for nested in value:
                reject_privileged(nested)

    reject_privileged(catalog)
    return {
        "catalog": dict(catalog),
        "pgm": pgm,
        "yaml": nav_yaml,
        "bundleSha256": _canonical_sha256(
            {
                "catalogSha256": _sha256(catalog_path.read_bytes()),
                "pgmSha256": _sha256(pgm),
                "yamlSha256": _sha256(nav_yaml),
            }
        ),
    }


def build_scene_pcd(bundle: Mapping[str, Any]) -> bytes:
    """Reconstruct deterministic ground/obstacle samples from the trusted PGM."""

    catalog = bundle["catalog"]
    map_binding = catalog["map"]
    width, height, cells = _pgm_bytes(bundle["pgm"])
    if width != int(map_binding["widthCells"]) or height != int(map_binding["heightCells"]):
        raise OfficeV2BootstrapError("Office V2 PGM dimensions changed")
    resolution = float(map_binding["resolution"])
    origin = map_binding["origin"]
    if not math.isfinite(resolution) or resolution <= 0 or not isinstance(origin, list) or len(origin) != 3:
        raise OfficeV2BootstrapError("Office V2 map geometry is invalid")
    origin_x, origin_y = float(origin[0]), float(origin[1])
    points: list[tuple[float, float, float]] = []
    for row in range(height):
        y = origin_y + (height - row - 0.5) * resolution
        for column in range(width):
            x = origin_x + (column + 0.5) * resolution
            points.append((x, y, 0.0))
            if cells[row * width + column] < 100:
                points.append((x, y, 0.40))
    maximum_x = origin_x + width * resolution
    maximum_y = origin_y + height * resolution
    points.extend(
        [
            (origin_x, origin_y, 0.0),
            (maximum_x, origin_y, 0.0),
            (origin_x, maximum_y, 0.0),
            (maximum_x, maximum_y, 0.0),
            (origin_x, origin_y, 3.0),
            (maximum_x, maximum_y, 3.0),
        ]
    )
    header = (
        "VERSION .7\n"
        "FIELDS x y z\n"
        "SIZE 4 4 4\n"
        "TYPE F F F\n"
        "COUNT 1 1 1\n"
        f"WIDTH {len(points)}\n"
        "HEIGHT 1\n"
        f"POINTS {len(points)}\n"
        "DATA ascii\n"
    )
    body = "".join(f"{x:.6f} {y:.6f} {z:.6f}\n" for x, y, z in points)
    return (header + body).encode("ascii")


