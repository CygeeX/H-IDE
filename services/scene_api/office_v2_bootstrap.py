class SceneApi:
    def __init__(self, base_url: str, public_token: str, internal_token: str) -> None:
        if not base_url.strip() or not public_token.strip() or not internal_token.strip():
            raise OfficeV2BootstrapError("Scene API URL and both tokens are required")
        self.base_url = base_url.rstrip("/")
        self.public = {"Authorization": f"Bearer {public_token}"}
        self.internal = {"Authorization": f"Bearer {internal_token}"}

    def request(
        self,
        method: str,
        path: str,
        *,
        internal: bool = False,
        expected: Sequence[int] = (200,),
        **kwargs: Any,
    ) -> httpx.Response:
        try:
            response = httpx.request(
                method,
                f"{self.base_url}{path}",
                headers={**(self.internal if internal else self.public), **kwargs.pop("headers", {})},
                timeout=30.0,
                trust_env=False,
                **kwargs,
            )
        except (httpx.TransportError, httpx.TimeoutException) as exc:
            raise OfficeV2BootstrapError(f"Scene API transport failed: {exc}") from exc
        if response.status_code not in expected:
            raise OfficeV2BootstrapError(
                f"Scene API {method} {path} returned {response.status_code}: {response.text[:500]}"
            )
        return response


def _wait_job(api: SceneApi, job_id: str, deadline: float) -> dict[str, Any]:
    while time.monotonic() < deadline:
        payload = api.request("GET", f"/api/v1/scene-jobs/{job_id}").json()
        status = payload.get("status")
        if status == "succeeded":
            return payload
        if status in {"failed", "cancelled"}:
            raise OfficeV2BootstrapError(
                f"Scene job {job_id} failed: {payload.get('errorCode')} {payload.get('message')}"
            )
        time.sleep(0.5)
    raise OfficeV2BootstrapError(f"Scene job {job_id} did not finish before the deadline")


def _annotations(catalog: Mapping[str, Any]) -> list[dict[str, Any]]:
    result: list[dict[str, Any]] = []
    for region in catalog["regions"]:
        result.append(
            {
                "locationId": region["regionId"],
                "name": region["name"],
                "aliases": list(region["aliases"]),
                "polygonXY": list(region["polygonXY"]),
                "zMin": 0.0,
                "zMax": 3.0,
                "entryPose": dict(region["entryPose"]),
            }
        )
        # Scan stations are product-safe navigation facts, not semantic object
        # answers. Publishing them through the ordinary annotation contract
        # lets Mission V2 resolve every stop from a reviewed SceneRef instead
        # of reading the evaluator-only scene source or embedding coordinates
        # in planner output.
        for station in region["stations"]:
            pose = dict(station["pose"])
            x = float(pose["x"])
            y = float(pose["y"])
            station_id = str(station["stationId"])
            result.append(
                {
                    "locationId": station_id,
                    "name": f"{region['name']} · {station_id}",
                    "aliases": [
                        station_id,
                        f"{station_id} scan station",
                    ],
                    "polygonXY": [
                        {"x": x - 0.10, "y": y - 0.10},
                        {"x": x + 0.10, "y": y - 0.10},
                        {"x": x + 0.10, "y": y + 0.10},
                        {"x": x - 0.10, "y": y + 0.10},
                    ],
                    "zMin": 0.0,
                    "zMax": 3.0,
                    "entryPose": pose,
                }
            )
    return result


def _find_existing(api: SceneApi, source_name: str, annotations: list[dict[str, Any]]) -> dict[str, Any] | None:
    scenes = api.request("GET", "/api/v1/scenes").json()
    for scene in scenes:
        if scene.get("sourceFileName") != source_name:
            continue
        for revision in reversed(scene.get("revisions", [])):
            if revision.get("status") != "published":
                continue
            if revision.get("annotations") == annotations and isinstance(revision.get("mapSummary"), Mapping):
                return {"sceneId": scene["sceneId"], "revision": revision["revision"]}
    return None


def install_and_bind(
    *,
    api: SceneApi,
    robot_id: str,
    timeout_seconds: float = 900.0,
    bundle_root: Path = BUNDLE_ROOT,
) -> dict[str, Any]:
    if not robot_id.strip():
        raise OfficeV2BootstrapError("robotId is required")
    bundle = load_bundle(bundle_root)
    annotations = _annotations(bundle["catalog"])
    source_name = f"office_v2_product_{bundle['bundleSha256'][:16]}.pcd"
    existing = _find_existing(api, source_name, annotations)
    deadline = time.monotonic() + timeout_seconds
    if existing is None:
        pcd = build_scene_pcd(bundle)
        created = api.request(
            "POST",
            "/api/v1/scene-uploads",
            json={"fileName": source_name, "sizeBytes": len(pcd)},
        ).json()
        upload_id = created["uploadId"]
        chunk_size = int(created["chunkSize"])
        for offset in range(0, len(pcd), chunk_size):
            chunk = pcd[offset : offset + chunk_size]
            checksum = base64.b64encode(hashlib.sha256(chunk).digest()).decode("ascii")
            api.request(
                "PATCH",
                f"/api/v1/scene-uploads/{upload_id}",
                headers={
                    "Content-Type": "application/octet-stream",
                    "Upload-Offset": str(offset),
                    "Upload-Checksum": f"sha256 {checksum}",
                },
                content=chunk,
            )
        completed = api.request(
            "POST", f"/api/v1/scene-uploads/{upload_id}/complete"
        ).json()
        _wait_job(api, completed["jobId"], deadline)
        scene_id = completed["sceneId"]
        scene = api.request("GET", f"/api/v1/scenes/{scene_id}").json()
        revision = max(scene["revisions"], key=lambda item: int(item["revision"]))["revision"]
        calibrated = api.request(
            "PUT",
            f"/api/v1/scenes/{scene_id}/revisions/{revision}/calibration",
            json={"calibration": identity_calibration().model_dump(mode="json")},
        ).json()
        map_job = calibrated.get("mapJob")
        if not isinstance(map_job, Mapping) or not isinstance(map_job.get("jobId"), str):
            raise OfficeV2BootstrapError("Scene API did not queue the Office V2 map job")
        _wait_job(api, map_job["jobId"], deadline)

        # Validate every scan pose against the Scene API's independently
        # derived occupancy artifact before publishing or binding the scene.
        for region in bundle["catalog"]["regions"]:
            for station in region["stations"]:
                pose = station["pose"]
                checked = api.request(
                    "POST",
                    f"/internal/v1/scenes/{scene_id}/revisions/{revision}/target-check",
                    internal=True,
                    json={"pointMap": {"x": pose["x"], "y": pose["y"], "z": pose["z"]}},
                ).json()
                if checked.get("classification") != "observed_free":
                    raise OfficeV2BootstrapError(
                        f"inspection station {station['stationId']} is not observed_free: {checked}"
                    )
        api.request(
            "PUT",
            f"/api/v1/scenes/{scene_id}/revisions/{revision}/annotations",
            json={"annotations": annotations},
        )
        api.request(
            "POST", f"/api/v1/scenes/{scene_id}/revisions/{revision}/publish"
        )
        existing = {"sceneId": scene_id, "revision": revision}

    api.request(
        "PUT",
        f"/api/v1/robots/{robot_id.strip()}/scene-binding",
        json=existing,
    )
    context = api.request(
        "GET",
        f"/internal/v1/robots/{robot_id.strip()}/scene-context",
        internal=True,
    ).json()
    expected_ref = {"sceneId": existing["sceneId"], "revision": existing["revision"]}
    if context.get("sceneRef") != expected_ref:
        raise OfficeV2BootstrapError("published Office V2 scene binding changed during verification")
    expected_locations = {
        item["regionId"] for item in bundle["catalog"]["regions"]
    } | {
        station["stationId"]
        for item in bundle["catalog"]["regions"]
        for station in item["stations"]
    }
    if {item.get("locationId") for item in context.get("annotations", [])} != expected_locations:
        raise OfficeV2BootstrapError("published Office V2 region catalog is incomplete")
    return {
        "status": "ready",
        "robotId": robot_id.strip(),
        "sceneRef": expected_ref,
        "catalogSha256": _sha256((bundle_root / CATALOG_PATH.name).read_bytes()),
        "bundleSha256": bundle["bundleSha256"],
        "regionIds": [item["regionId"] for item in bundle["catalog"]["regions"]],
        "stationIds": [
            station["stationId"]
            for item in bundle["catalog"]["regions"]
            for station in item["stations"]
        ],
    }


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--robot-id", default=os.getenv("SIMULATION_ROBOT_AGENT_ID", "g1-sim"))
    parser.add_argument("--base-url", default=os.getenv("SCENE_API_URL", "http://127.0.0.1:8090"))
    parser.add_argument("--public-token", default=os.getenv("SCENE_API_TOKEN") or os.getenv("CONTROL_API_TOKEN"))
    parser.add_argument("--internal-token", default=os.getenv("SCENE_API_INTERNAL_TOKEN"))
    parser.add_argument("--timeout-seconds", type=float, default=900.0)
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    result = install_and_bind(
        api=SceneApi(args.base_url, args.public_token or "", args.internal_token or ""),
        robot_id=args.robot_id,
        timeout_seconds=args.timeout_seconds,
    )
    print(json.dumps(result, ensure_ascii=False, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
